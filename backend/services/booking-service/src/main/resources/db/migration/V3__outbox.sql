-- Build step 6: transactional outbox (DESIGN.md §11).
-- An event is INSERTed here in the same transaction as the state change it describes, so "booking changed"
-- and "event will be sent" commit together. OutboxRelay publishes unpublished rows to Kafka.
CREATE TABLE outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id VARCHAR(64)    NOT NULL,   -- bookingId, used as the Kafka key (per-booking ordering)
    topic        VARCHAR(255)   NOT NULL,
    event_type   VARCHAR(255)   NOT NULL,   -- event class, so the relay can rebuild the object
    payload      VARCHAR(20000) NOT NULL,   -- event as JSON
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE              -- NULL = not sent yet
);

-- The relay's hot query: unpublished rows in id order
CREATE INDEX idx_outbox_unpublished ON outbox (id) WHERE published_at IS NULL;
