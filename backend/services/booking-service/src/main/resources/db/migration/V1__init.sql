-- Baseline schema for booking-service on PostgreSQL.
-- Same tables and columns as the previous MySQL baseline (it never ran on PostgreSQL, so V1 was rewritten).
-- Never edit this file after it has run: add V2__..., V3__... for later changes.
--
-- Enums are stored as text (VARCHAR) without CHECK constraints: adding a new status in Java
-- (e.g. AWAITING_PAYMENT) then needs no migration.

CREATE TABLE bookings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference  VARCHAR(255) NOT NULL,
    user_id            BIGINT,
    flight_id          BIGINT,
    flight_instance_id BIGINT,
    airline_id         BIGINT       NOT NULL,
    trip_type          SMALLINT CHECK (trip_type BETWEEN 0 AND 2),   -- ordinal of TripType
    cabin_class        VARCHAR(255),
    fare_id            BIGINT,
    flexible_ticket    BOOLEAN      NOT NULL,
    ticket_time_limit  TIMESTAMP(6),
    payment_id         BIGINT,
    status             VARCHAR(255),                                 -- BookingStatus (saga state)
    booking_date       TIMESTAMP(6),
    last_modified      TIMESTAMP(6),
    ticket_issued      BOOLEAN      NOT NULL,
    email              VARCHAR(255),                                 -- ContactInfo (embedded)
    phone              VARCHAR(255),
    CONSTRAINT uk_bookings_booking_reference UNIQUE (booking_reference)
);

CREATE TABLE passengers (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name                     VARCHAR(255) NOT NULL,
    last_name                      VARCHAR(255) NOT NULL,
    email                          VARCHAR(255),
    phone                          VARCHAR(255),
    date_of_birth                  DATE         NOT NULL,
    gender                         VARCHAR(255) NOT NULL,
    passport_number                VARCHAR(255),
    nationality                    VARCHAR(255),
    frequent_flyer_number          VARCHAR(255),
    primary_user_id                BIGINT,
    requires_wheelchair_assistance BOOLEAN,
    dietary_preferences            VARCHAR(255),
    medical_conditions             VARCHAR(255),
    booking_id                     BIGINT REFERENCES bookings (id),
    is_active                      BOOLEAN      NOT NULL,
    version                        BIGINT,
    created_at                     TIMESTAMP(6),
    updated_at                     TIMESTAMP(6)
);

CREATE TABLE tickets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number    VARCHAR(255) NOT NULL,
    status           VARCHAR(255),                                   -- TicketStatus
    issued_at        TIMESTAMP(6),
    booking_id       BIGINT REFERENCES bookings (id),
    passenger_id     BIGINT REFERENCES passengers (id),
    seat_instance_id BIGINT,                                         -- cross-service ref (seat-service)
    CONSTRAINT uk_tickets_ticket_number UNIQUE (ticket_number)
);

-- Cross-service id lists (ancillary-service), one row per selected item
CREATE TABLE booking_ancillaries (
    booking_id   BIGINT NOT NULL REFERENCES bookings (id),
    ancillary_id BIGINT
);

CREATE TABLE booking_meals (
    booking_id BIGINT NOT NULL REFERENCES bookings (id),
    meal_id    BIGINT
);

-- PostgreSQL does not index foreign keys automatically (MySQL did)
CREATE INDEX idx_passengers_booking_id         ON passengers (booking_id);
CREATE INDEX idx_tickets_booking_id            ON tickets (booking_id);
CREATE INDEX idx_tickets_passenger_id          ON tickets (passenger_id);
CREATE INDEX idx_booking_ancillaries_booking_id ON booking_ancillaries (booking_id);
CREATE INDEX idx_booking_meals_booking_id       ON booking_meals (booking_id);
